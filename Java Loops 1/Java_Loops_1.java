
import java.util.*;

public class Java_Loops_1 {
  
    public static void main(String[] args){
      
        Scanner sc = new Scanner(System.in);
      
        int a = sc.nextInt();
      
        for (int b = 1; b <= 10; b++){
          
            System.out.println(a +" x " + b + " = " + (a * b));
          
        }
      
    }
  
}
